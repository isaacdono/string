import uuid
from datetime import datetime, timezone
from sqlalchemy import Column, String, Integer, Numeric, DateTime, ForeignKey, Text, JSON
from sqlalchemy.dialects.postgresql import UUID as PG_UUID
from sqlalchemy.orm import relationship
from .database import Base


class Campaign(Base):
    __tablename__ = "campaigns"

    id = Column(
        PG_UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        index=True,
        doc="Primary UUID key for the drop campaign",
    )
    handle = Column(
        String(255),
        nullable=False,
        index=True,
        doc="Creator handle, e.g. @criador",
    )
    description = Column(
        Text,
        nullable=True,
        doc="Creator product idea, niche, or prompt",
    )
    status = Column(
        String(50),
        nullable=False,
        default="pending",
        index=True,
        doc="Campaign status: pending, active, ended",
    )
    product_type = Column(
        String(50),
        nullable=True,
        doc="Product type: physical, digital",
    )
    price = Column(
        Numeric(10, 2),
        nullable=True,
        doc="Unit price in BRL (e.g. 97.00)",
    )
    theme_config = Column(
        JSON,
        nullable=True,
        default=dict,
        doc="Visual theme colors and avatar URL (primary, background, foto_url)",
    )
    copy_data = Column(
        JSON,
        nullable=True,
        default=dict,
        doc="Copywriting structure (title, subtitle, hooks, benefits)",
    )
    scarcity_limit = Column(
        Integer,
        nullable=True,
        doc="Max units available for physical scarcity drops",
    )
    blueprint_content = Column(
        Text,
        nullable=True,
        doc="Strategic marketing roadmap and copy plan generated by AI",
    )
    pdf_url = Column(
        String(500),
        nullable=True,
        doc="URL to download the generated PDF blueprint",
    )
    expires_at = Column(
        DateTime(timezone=True),
        nullable=True,
        doc="Expiration timestamp for time-based urgency drops",
    )
    created_at = Column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        doc="Timestamp when campaign was registered",
    )

    orders = relationship("Order", back_populates="campaign", cascade="all, delete-orphan")


class Order(Base):
    __tablename__ = "orders"

    id = Column(
        PG_UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        index=True,
        doc="Primary UUID key for the order",
    )
    campaign_id = Column(
        PG_UUID(as_uuid=True),
        ForeignKey("campaigns.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        doc="Foreign key to the associated campaign",
    )
    asaas_payment_id = Column(
        String(255),
        nullable=True,
        index=True,
        doc="Asaas transaction/payment identifier",
    )
    buyer_name = Column(
        String(255),
        nullable=False,
        doc="Full name of the purchaser",
    )
    buyer_email = Column(
        String(255),
        nullable=False,
        doc="Email address for receipt and delivery",
    )
    buyer_cpf = Column(
        String(50),
        nullable=False,
        doc="Buyer CPF document number",
    )
    buyer_address = Column(
        JSON,
        nullable=True,
        doc="Shipping address for physical drops",
    )
    status = Column(
        String(50),
        nullable=False,
        default="PENDING",
        index=True,
        doc="Payment status: PENDING, PAID, FAILED",
    )
    created_at = Column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        doc="Timestamp when the checkout was initiated",
    )

    campaign = relationship("Campaign", back_populates="orders")
